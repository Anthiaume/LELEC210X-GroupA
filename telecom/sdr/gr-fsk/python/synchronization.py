class synchronization(gr.basic_block):
    """
    docstring for block synchronization
    """

    def __init__(self, drate, N_Moose, fdev, fsamp, hdr_len, packet_len, Grx, enable_log):
        self.drate = drate
        self.fdev = fdev
        self.fsamp = fsamp
        self.osr = int(fsamp / drate)
        self.hdr_len = hdr_len
        self.packet_len = packet_len  # in bytes
        self.estimated_noise_power = None
        self.Grx = Grx
        self.enable_log = enable_log
        self.N_Moose = N_Moose

        # Remaining number of samples in the current packet
        self.rem_samples = 0
        self.init_sto = 0
        self.cfo = 0.0
        self.t0 = 0.0
        self.estimated_noise_power  = None
        self.estimated_signal_power = 0

        gr.basic_block.__init__(
            self, name="Synchronization", in_sig=[np.complex64], out_sig=[np.complex64]
        )
        self.logger = logging.getLogger("sync")
        self.message_port_register_in(pmt.intern("NoisePow"))
        self.set_msg_handler(pmt.intern("NoisePow"), self.handle_msg_noise)


        self.message_port_register_in(pmt.intern("SignalPow"))
        self.set_msg_handler(pmt.intern("SignalPow"), self.handle_msg_signal)

        self.gr_version = gr.version()

    def forecast(self, noutput_items, ninputs):
        """
        Forecast is only called from a general block
        this is the default implementation
        """
        ninput_items_required = [0] * ninputs
        for i in range(ninputs):
            if self.rem_samples == 0:  # looking for a new packet
                ninput_items_required[i] = min(
                    8000, 8 * self.osr * (self.packet_len + 1) + self.osr
                )  # enough samples to find a header inside
            else:  # processing a previously found packet
                ninput_items_required[i] = (
                    noutput_items  # pass remaining samples in packet to next block
                )

        return ninput_items_required

    def set_enable_log(self, enable_log):
        self.enable_log = enable_log

    def handle_msg_noise(self, msg):
        if pmt.is_pair(msg):
            self.estimated_noise_power = pmt.to_float(pmt.cdr(msg))
        else:
            self.estimated_noise_power = pmt.to_float(msg)

    def handle_msg_signal(self, msg):
        self.estimated_signal_power = pmt.to_float(msg)

    def set_Grx(self, Grx):
        self.Grx = Grx

    def general_work(self, input_items, output_items):
        if self.rem_samples == 0:  # new packet to process, compute the CFO and STO
            y = input_items[0][: self.hdr_len * 8 * self.osr]
            self.cfo = cfo_estimation(y, self.drate, self.osr, self.fdev, self.N_Moose)

            # Correct CFO in preamble
            t = np.arange(len(y)) / (self.drate * self.osr)
            y_cfo = np.exp(-1j * 2 * np.pi * self.cfo * t) * y
            self.t0 = t[-1]

            sto = sto_estimation(y_cfo, self.drate, self.osr, self.fdev)

            self.init_sto = sto
            self.power_est   = 0
            self.rem_samples = (self.packet_len + 1) * 8 * self.osr

            self.consume_each(sto)  # drop *sto* samples to align the buffer
            return 0  # ... but we do not transmit data to the demodulation stage
        else:
            win_size = min(len(output_items[0]), self.rem_samples)
            y = input_items[0][:win_size]

            # Correct CFO before transferring samples to demodulation stage
            t = self.t0 + np.arange(1, len(y) + 1) / (self.drate * self.osr)
            y_corr = np.exp(-1j * 2 * np.pi * self.cfo * t) * y
            self.t0 = t[
                -1
            ]  # we keep the CFO correction continuous across buffer chunks

            output_items[0][:win_size] = y_corr

            self.rem_samples -= win_size
            if (self.rem_samples == 0):  # Thow away the extra OSR samples from the preamble detection stage

                # No Noise estimation has been performed yet
                if self.estimated_noise_power is None:
                    if self.enable_log:
                        self.logger.info(
                            f"CFO {self.cfo:.2f} Hz, STO {self.init_sto}, Avg. Amplitude: {np.mean(np.abs(y)):.2e}"
                        )

                # A noise estimation has already been performed
                else :
                    SNR_est = self.osr*( (self.estimated_signal_power) - self.estimated_noise_power ) / self.estimated_noise_power
                    if self.enable_log:
                        self.logger.info(
                            f"CFO {self.cfo:.2f} Hz, STO {self.init_sto}, EsN0est: {10 * np.log10(SNR_est):.2f} dB, Avg. Amplitude: {np.sqrt(np.abs(self.estimated_signal_power)):.2e}"
                        )
                    measurements_logger.info(f"CFO={self.cfo},STO={self.init_sto}")
                    measurements_logger.info(f"EsN0dB={10 * np.log10(SNR_est):.2f},GRXdB={self.Grx},N0={self.estimated_noise_power}")

                self.consume_each(win_size + self.osr - self.init_sto)
            else:
                self.consume_each(win_size)

            return win_size